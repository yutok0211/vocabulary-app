PREFECTURES = [
    "北海道", "青森県", "岩手県", "宮城県", "秋田県", "山形県", "福島県", "茨城県", "栃木県", "群馬県",
    "埼玉県", "千葉県", "東京都", "神奈川県", "新潟県", "富山県", "石川県", "福井県", "山梨県", "長野県",
    "岐阜県", "静岡県", "愛知県", "三重県", "滋賀県", "京都府", "大阪府", "兵庫県", "奈良県", "和歌山県",
    "鳥取県", "島根県", "岡山県", "広島県", "山口県", "徳島県", "香川県", "愛媛県", "高知県", "福岡県",
    "佐賀県", "長崎県", "熊本県", "大分県", "宮崎県", "鹿児島県", "沖縄県",
]


def resolve(name: str) -> str:
    """「東京」「大阪」のような省略形も受け付けて正式名を返す。"""
    name = name.strip()
    for p in PREFECTURES:
        if name in (p, p.rstrip("都府県")) or (name == "北海道" and p == "北海道"):
            return p
    raise ValueError(f"都道府県名が不明です: {name}")


def iso_code(name: str) -> str:
    """ISO 3166-2 コード（例: 東京都 → JP-13）。"""
    return f"JP-{PREFECTURES.index(resolve(name)) + 1:02d}"
